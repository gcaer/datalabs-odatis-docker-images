#!/usr/bin/env python
"""Fast lock of an image environment with pixi, converted to conda-lock.yml.

1. merge the environment.yml files into <image>/pixi.toml (generated, do not edit)
2. `pixi lock` (rattler + uv solvers, reuses the existing <image>/pixi.lock)
3. convert <image>/pixi.lock to <image>/conda-lock.yml, the format expected by
   the ONBUILD `conda-lock install` step of cnes/base-image

Usage: python pixi_lock.py [image]   (default: vreodatis)
"""
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

import yaml

PLATFORM = "linux-64"
IMAGE = sys.argv[1] if len(sys.argv) > 1 else "vreodatis"
ROOT = Path(__file__).resolve().parent
IMAGE_DIR = ROOT / IMAGE
SOURCES = [
    "environment.yml",
    "../.base_layer/base-notebook-environment.yml",
    "../.base_layer/pangeo-notebook-environment.yml",
]

SPEC_RE = re.compile(r"^([A-Za-z0-9_.\-]+)\s*(.*)$")


def to_pixi_spec(constraint):
    """Convert the version part of a conda MatchSpec to a pixi version spec."""
    constraint = constraint.replace(" ", "")
    if not constraint:
        return "*"
    if constraint.startswith("=") and not constraint.startswith("=="):
        version = constraint[1:]
        return version if version.endswith("*") else f"{version}.*"
    return constraint


def merge(specs, name, constraint, pinned):
    """Combine constraints; a version given in the image environment.yml
    (first source) overrides the base layers ones."""
    if name in pinned:
        return
    current = specs.get(name, "*")
    if constraint == "*" or constraint == current:
        specs.setdefault(name, "*")
    elif current == "*":
        specs[name] = constraint
    else:
        specs[name] = f"{current},{constraint}"


def write_pixi_toml():
    channels, conda, pypi = [], {}, {}
    pinned_conda, pinned_pypi = set(), set()
    for i, source in enumerate(SOURCES):
        env = yaml.safe_load((IMAGE_DIR / source).read_text())
        channels += [c for c in env.get("channels", []) if c != "nodefaults" and c not in channels]
        for dep in env.get("dependencies", []):
            if isinstance(dep, dict):
                for req in dep.get("pip", []):
                    name, constraint = SPEC_RE.match(req.strip()).groups()
                    merge(pypi, name, constraint.replace(" ", "") or "*", pinned_pypi)
                continue
            name, constraint = SPEC_RE.match(dep.strip()).groups()
            merge(conda, name, to_pixi_spec(constraint), pinned_conda)
        if i == 0:
            pinned_conda = {n for n, s in conda.items() if s != "*"}
            pinned_pypi = {n for n, s in pypi.items() if s != "*"}

    q = json.dumps
    lines = [
        "# Generated by pixi_lock.py from " + ", ".join(SOURCES) + ". DO NOT EDIT!",
        "[workspace]",
        f"name = {q(IMAGE)}",
        f"channels = {q(channels)}",
        f"platforms = {q([PLATFORM])}",
        "",
        "[dependencies]",
        *(f"{q(n)} = {q(s)}" for n, s in sorted(conda.items())),
    ]
    if pypi:
        lines += ["", "[pypi-dependencies]", *(f"{q(n)} = {q(s)}" for n, s in sorted(pypi.items()))]
    (IMAGE_DIR / "pixi.toml").write_text("\n".join(lines) + "\n")


def split_dep(dep):
    name, _, spec = dep.strip().partition(" ")
    return name, spec.strip()


def conda_entry(pkg):
    filename = pkg["conda"].rsplit("/", 1)[1]
    stem = re.sub(r"(\.conda|\.tar\.bz2)$", "", filename)
    name, version, _build = stem.rsplit("-", 2)
    return {
        "name": name,
        "version": version,
        "manager": "conda",
        "platform": PLATFORM,
        "dependencies": dict(split_dep(d) for d in pkg.get("depends", [])),
        "url": pkg["conda"],
        "hash": {"md5": pkg["md5"], "sha256": pkg["sha256"]},
        "category": "main",
        "optional": False,
    }


def pypi_entry(pkg):
    deps = {}
    for req in pkg.get("requires_dist", []):
        if "extra ==" in req:
            continue
        req = req.split(";")[0].strip()
        name, constraint = SPEC_RE.match(req).groups()
        deps[name] = constraint.strip("() ") or "*"
    return {
        "name": pkg["name"],
        "version": pkg["version"],
        "manager": "pip",
        "platform": PLATFORM,
        "dependencies": deps,
        "url": pkg["pypi"],
        "hash": {"sha256": pkg["sha256"]},
        "category": "main",
        "optional": False,
    }


def write_conda_lock():
    lock = yaml.safe_load((IMAGE_DIR / "pixi.lock").read_text())
    env = lock["environments"]["default"]
    wanted = {next(iter(p.values())) for p in env["packages"][PLATFORM]}

    packages = []
    for pkg in lock["packages"]:
        if "conda" in pkg and pkg["conda"] in wanted:
            packages.append(conda_entry(pkg))
        elif "pypi" in pkg and pkg["pypi"] in wanted:
            packages.append(pypi_entry(pkg))
    packages.sort(key=lambda p: (p["manager"] != "conda", p["name"]))

    # conda-lock install does not check content_hash, use the hash of the pixi inputs
    digest = hashlib.sha256((IMAGE_DIR / "pixi.toml").read_bytes()).hexdigest()
    content = {
        "version": 1,
        "metadata": {
            "content_hash": {PLATFORM: digest},
            "channels": [{"url": c["url"].rstrip("/").rsplit("/", 1)[-1], "used_env_vars": []}
                         for c in env["channels"]],
            "platforms": [PLATFORM],
            "sources": SOURCES,
        },
        "package": packages,
    }
    header = (
        "# This lock file was generated by pixi_lock.py from pixi.lock (pixi lock + conversion). DO NOT EDIT!\n"
        "#\n"
        "# Install this environment as \"YOURENV\" with:\n"
        "#     conda-lock install -n YOURENV conda-lock.yml\n"
        "# To re-solve the environment, after changing environment.yml or the base layer:\n"
        f"#     pixi run lock {IMAGE}\n"
    )
    (IMAGE_DIR / "conda-lock.yml").write_text(header + yaml.safe_dump(content, sort_keys=False, width=1000))
    return packages


def main():
    write_pixi_toml()
    subprocess.run(["pixi", "lock", "--manifest-path", str(IMAGE_DIR / "pixi.toml")], check=True)
    packages = write_conda_lock()
    n_pip = sum(p["manager"] == "pip" for p in packages)
    print(f"{IMAGE}/conda-lock.yml: {len(packages) - n_pip} conda + {n_pip} pip packages")


if __name__ == "__main__":
    main()
